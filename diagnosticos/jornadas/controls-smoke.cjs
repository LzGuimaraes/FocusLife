const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const app = process.env.JORNADAS_APP_URL || 'http://localhost:5179';
const api = process.env.JORNADAS_API_URL || 'http://localhost:18089';
for (const url of [app, api]) assert.ok(['localhost', '127.0.0.1'].includes(new URL(url).hostname), 'Use serviços locais de teste');
assert.ok(process.env.JORNADAS_TEST_EMAIL && process.env.JORNADAS_TEST_PASSWORD, 'Informe uma conta local de teste');
const artifacts = process.env.JORNADAS_ARTIFACTS || '/tmp';
const hoje = new Intl.DateTimeFormat('en-CA', { timeZone: 'America/Cuiaba', year: 'numeric', month: '2-digit', day: '2-digit' }).format(new Date());
const dateLabel = value => new Intl.DateTimeFormat('pt-BR', { day: 'numeric', month: 'long', year: 'numeric' }).format(new Date(`${value}T12:00:00`));
const offset = n => { const date = new Date(`${hoje}T12:00:00Z`); date.setUTCDate(date.getUTCDate() + n); return date.toISOString().slice(0, 10); };
(async () => {
 fs.mkdirSync(artifacts, { recursive: true });
 const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || undefined, headless: true, args: ['--no-sandbox'] });
 const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
 const errors = []; page.on('pageerror', error => errors.push(error.message));
 const title = `Teste de controles ${Date.now()}`;
 let activityId;
 try {
  await page.addInitScript(() => { if (!localStorage.getItem('fl-theme')) localStorage.setItem('fl-theme', 'light'); });
  await page.goto(`${app}/auth/login`);
  await page.getByLabel(/^E-mail/).fill(process.env.JORNADAS_TEST_EMAIL);
  await page.getByLabel(/^Senha/).fill(process.env.JORNADAS_TEST_PASSWORD);
  await page.getByRole('button', { name: 'Entrar', exact: true }).click(); await page.waitForURL('**/dashboard');
  await page.goto(`${app}/jornadas`);
  await page.getByRole('button', { name: /Nova atividade/ }).first().click();
  const form = page.getByRole('dialog', { name: 'Nova atividade', exact: true });
  await form.getByLabel(/^Título/).fill(title);
  await form.getByRole('button', { name: 'Calendário de data de início', exact: true }).click();
  let calendar = page.getByRole('dialog', { name: 'Calendário: Data de início', exact: true });
  await calendar.getByRole('button', { name: dateLabel(hoje), exact: true }).waitFor();
  await page.keyboard.press('ArrowRight');
  assert.equal(await page.evaluate(() => document.activeElement.dataset.date), offset(1));
  await page.keyboard.press('Escape');
  assert.equal(await form.count(), 1); assert.equal(await calendar.count(), 0);
  await form.getByRole('button', { name: 'Calendário de data de início', exact: true }).click();
  await calendar.getByRole('button', { name: 'Mês anterior', exact: true }).click();
  await calendar.getByRole('button', { name: 'Próximo mês', exact: true }).click();
  await calendar.getByRole('button', { name: dateLabel(hoje), exact: true }).click();
  assert.equal(await form.getByLabel('Data de início', { exact: true }).inputValue(), hoje);
  await form.getByLabel('Prazo previsto', { exact: true }).fill(offset(10));
  await form.getByRole('button', { name: 'Calendário de prazo previsto', exact: true }).click();
  calendar = page.getByRole('dialog', { name: 'Calendário: Prazo previsto', exact: true });
  const forbidden = calendar.getByRole('button', { name: dateLabel(offset(-1)), exact: true });
  if (await forbidden.count()) assert.ok(await forbidden.isDisabled());
  await calendar.getByRole('button', { name: dateLabel(offset(10)), exact: true }).click();
  await form.getByRole('combobox', { name: 'Unidade de medida', exact: true }).click();
  await page.getByRole('option', { name: 'Unidade personalizada…', exact: true }).click();
  await form.getByLabel('Nome da unidade', { exact: true }).fill('capítulos');
  const status = form.getByRole('combobox', { name: 'Status', exact: true });
  await status.focus(); await page.keyboard.press('ArrowDown'); await page.keyboard.press('ArrowDown'); await page.keyboard.press('Enter');
  assert.match(await status.textContent(), /Em andamento/);
  await form.getByRole('combobox', { name: 'Prioridade (opcional)', exact: true }).click();
  await page.getByRole('option', { name: 'Alta', exact: true }).click();
  assert.match(await form.getByRole('combobox', { name: 'Prioridade (opcional)', exact: true }).textContent(), /Alta/);
  await form.getByRole('checkbox', { name: 'Seg', exact: true }).check();
  await form.getByRole('button', { name: 'Calendário de data de referência do saldo (fim do dia)', exact: true }).click();
  calendar = page.getByRole('dialog', { name: 'Calendário: Data de referência do saldo (fim do dia)', exact: true });
  assert.ok(await calendar.getByRole('button', { name: dateLabel(offset(1)), exact: true }).isDisabled());
  await page.screenshot({ path: `${artifacts}/jornadas-calendar-light.png` });
  await page.keyboard.press('Escape');
  const created = page.waitForResponse(r => r.url().endsWith('/jornadas') && r.request().method() === 'POST');
  await form.getByRole('button', { name: 'Salvar atividade', exact: true }).click();
  const response = await created; const record = await response.json(); assert.ok(response.ok(), JSON.stringify(record)); activityId = record.id;
  assert.equal(record.inicio, hoje); assert.equal(record.prazo, offset(10)); assert.equal(record.prioridade, 'alta'); assert.equal(record.unidade, 'capítulos'); assert.deepEqual(record.diasSemana, ['MONDAY']);
  const remove = page.getByRole('button', { name: `Excluir atividade ${title}`, exact: true }); await remove.waitFor();
  await page.getByRole('button', { name: 'Alternar tema claro/escuro', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 }); await page.waitForTimeout(350);
  const filter = page.getByRole('combobox', { name: 'Status', exact: true }); await filter.click();
  await page.getByRole('listbox').waitFor(); await page.screenshot({ path: `${artifacts}/jornadas-select-mobile-dark.png` });
  const bounds = await page.getByRole('listbox').boundingBox(); assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= 391);
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: /Nova atividade/ }).first().click();
  await form.getByRole('button', { name: 'Calendário de data de início', exact: true }).click();
  calendar = page.getByRole('dialog', { name: 'Calendário: Data de início', exact: true });
  await page.screenshot({ path: `${artifacts}/jornadas-calendar-mobile-dark.png` });
  const rect = await calendar.boundingBox(); assert.ok(rect.x >= 0 && rect.x + rect.width <= 391);
  await page.keyboard.press('Escape'); assert.equal(await form.count(), 1); await page.keyboard.press('Escape'); await form.waitFor({ state: 'hidden' });
  await remove.click(); const confirmation = page.getByRole('dialog', { name: 'Excluir atividade', exact: true });
  await confirmation.getByRole('button', { name: 'Cancelar', exact: true }).click();
  assert.equal((await page.request.get(`${api}/jornadas/${activityId}`)).status(), 200);
  await remove.click();
  const deleted = page.waitForResponse(r => r.url().includes(`/jornadas/${activityId}?`) && r.request().method() === 'DELETE');
  await confirmation.getByRole('button', { name: 'Excluir atividade', exact: true }).click(); assert.ok((await deleted).ok());
  await remove.waitFor({ state: 'hidden' }); assert.equal((await page.request.get(`${api}/jornadas/${activityId}`)).status(), 404); activityId = undefined;
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)); assert.deepEqual(errors, []);
  console.log(JSON.stringify({ ok: true, flows: ['calendário por mouse e teclado', 'limites de início e saldo', 'seletores de status e prioridade', 'dias selecionados persistidos', 'temas claro/escuro e celular', 'Escape fecha só o calendário', 'exclusão no card com confirmação e cancelamento'] }));
 } catch (error) { await page.screenshot({ path: `${artifacts}/jornadas-controls-failure.png`, fullPage: true }); throw error; }
 finally {
  if (activityId) { const r = await page.request.get(`${api}/jornadas/${activityId}`); if (r.ok()) { const a = await r.json(); await page.request.delete(`${api}/jornadas/${activityId}?version=${a.version}`); } }
  await browser.close();
 }
})().catch(error => { console.error(error); process.exitCode = 1; });

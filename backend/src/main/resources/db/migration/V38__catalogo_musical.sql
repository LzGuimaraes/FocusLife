-- Catálogo compartilhado: o admin gerencia e os usuários sorteiam por estilo.
CREATE TABLE IF NOT EXISTS musica_estilo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(80) NOT NULL,
    nome_chave VARCHAR(80) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS musica_video (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estilo_id BIGINT NOT NULL REFERENCES musica_estilo(id),
    url VARCHAR(255) NOT NULL,
    youtube_id VARCHAR(11) NOT NULL,
    CONSTRAINT uk_musica_video_estilo_youtube UNIQUE (estilo_id, youtube_id)
);

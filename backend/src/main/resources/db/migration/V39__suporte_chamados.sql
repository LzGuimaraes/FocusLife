CREATE TABLE IF NOT EXISTS suporte_chamado (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES tb_user(id) ON DELETE CASCADE,
    solicitacao_id UUID NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    titulo VARCHAR(120) NOT NULL,
    descricao VARCHAR(4000) NOT NULL,
    usuario_nome VARCHAR(255) NOT NULL,
    usuario_email VARCHAR(255) NOT NULL,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    email_enviado BOOLEAN NOT NULL DEFAULT FALSE,
    email_enviado_em TIMESTAMP WITH TIME ZONE,
    tentativas INTEGER NOT NULL DEFAULT 0,
    ultima_tentativa_em TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_suporte_usuario_solicitacao UNIQUE (user_id, solicitacao_id)
);
CREATE INDEX IF NOT EXISTS idx_suporte_usuario_data ON suporte_chamado(user_id, criado_em DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_suporte_pendentes ON suporte_chamado(email_enviado, tentativas, criado_em);
